import { createHash } from 'node:crypto';
import { readdir, stat, writeFile } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';
import type { Plugin } from 'vite';

/**
 * The web app's service worker (#42), so it opens and works offline once installed:
 * - The app's files are cached when the worker installs, and served from the cache first.
 * - Page loads try the network, and fall back to the cached app when offline.
 * - Anything else (Supabase, other sites, the viewer at /viewer/, the old /app/ address) passes
 *   straight through; data syncs on its own.
 * - A new version waits until every window of the app is closed, so an open session never mixes
 *   old and new files.
 */
export function serviceWorkerSource(files: readonly string[], version: string): string {
  return `// Generated by build/serviceWorker.ts. Do not edit.
const CACHE = ${JSON.stringify(`setlist-app-${version}`)};
const FILES = ${JSON.stringify(files)};
const scope = new URL(self.registration.scope);
const INDEX = new URL('index.html', scope).href;
// Other parts of the site, under the app's scope but not the app's.
const ELSEWHERE = ['viewer/', 'app/'].map((path) => new URL(path, scope).pathname);

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(FILES.map((file) => new URL(file, scope).href))),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      for (const key of await caches.keys()) {
        if (key.startsWith('setlist-app-') && key !== CACHE) await caches.delete(key);
      }
      await self.clients.claim();
    })(),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== scope.origin || !url.pathname.startsWith(scope.pathname)) return;
  if (ELSEWHERE.some((path) => url.pathname.startsWith(path))) return;

  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request).catch(async () => (await caches.match(INDEX)) ?? Response.error()),
    );
    return;
  }
  event.respondWith(caches.match(request).then((cached) => cached ?? fetch(request)));
});
`;
}

async function listFiles(dir: string, root = dir): Promise<string[]> {
  const files: string[] = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) files.push(...(await listFiles(path, root)));
    else files.push(relative(root, path).split(sep).join('/'));
  }
  return files;
}

/** Writes sw.js into the build output, listing every file the build produced. */
export function serviceWorkerPlugin(): Plugin {
  let outDir = 'dist';
  return {
    name: 'setlist-service-worker',
    apply: 'build',
    configResolved(config) {
      outDir = config.build.outDir;
    },
    async closeBundle() {
      const files = (await listFiles(outDir))
        .filter((file) => file !== 'sw.js' && !file.endsWith('.map'))
        .sort();
      // Hashed file names change with their content, so their names and sizes identify a build.
      const hash = createHash('sha256');
      for (const file of files) hash.update(`${file}:${(await stat(join(outDir, file))).size}\n`);
      const version = hash.digest('hex').slice(0, 12);
      await writeFile(join(outDir, 'sw.js'), serviceWorkerSource(files, version));
    },
  };
}
